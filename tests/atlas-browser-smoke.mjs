import { chromium } from 'playwright';

const root = process.env.ATLAS_URL || 'http://127.0.0.1:8000';
const browser = await chromium.launch({headless:true});
const errors=[];
function assert(value,msg){if(!value)throw new Error('BROWSER SMOKE: '+msg);}
async function ready(page){
  page.on('pageerror', e=>errors.push(e.message));
  page.on('console', msg=>{if(msg.type()==='error')errors.push(msg.text());});
}
try {
  const page=await browser.newPage({viewport:{width:1366,height:900}});
  await ready(page);
  await page.goto(root+'/atlas/',{waitUntil:'networkidle'});
  await page.getByRole('heading',{name:'Find the teaching, then read the original.'}).waitFor();
  assert(await page.getByRole('button',{name:/knowledge, method, and spiritual development/i}).count()>0,'six-region navigation missing');
  await page.locator('#search').fill('Manas');
  await page.locator('#search-results [data-node="RS-09.05.01"]').first().click();
  await page.waitForURL(/#node=RS-09.05.01/);
  await page.getByText('spirit-self / Manas',{exact:true}).first().waitFor();
  assert(await page.getByRole('heading',{name:'Passage-linked relationships'}).count()===1,'concept page evidence panel missing');
  await page.goto(root+'/atlas/graph.html',{waitUntil:'networkidle'});
  await page.getByRole('heading',{name:'Follow the evidence between teachings'}).waitFor();
  const initial=await page.locator('#relations tr').count();
  assert(initial>=209,'expected at least 209 source-linked graph rows, got '+initial);
  await page.locator('#family-filter').selectOption('distinction_and_comparison');
  const contrastRows=await page.locator('#relations [data-edge]').count();
  assert(contrastRows>0 && contrastRows<initial,'semantic relation family filter not functional');
  await page.locator('#clear-filters').click();
  assert(await page.locator('#relations tr').count()===initial,'family-filter reset failed');
  await page.locator('#domain-filter').selectOption('07');
  const domainRows=await page.locator('#relations tr').count();
  assert(domainRows>0 && domainRows<initial,'domain filter not working');
  await page.locator('#domain-filter').selectOption('09');
  await page.locator('#evidence-filter').selectOption('editorial_comparison');
  const compared=await page.locator('#relations [data-edge]').count();
  assert(compared>=1 && compared<domainRows,'editorial filter not working');
  await page.locator('#clear-filters').click();
  assert(await page.locator('#relations tr').count()===initial,'reset filters failed');
  await page.locator('#source-filter').selectOption('SG-GA009-C01');
  const sourceRows=await page.locator('#relations [data-edge]').count();
  assert(sourceRows>0 && sourceRows<initial,'source filter failed');
  await page.locator('#relations [data-edge]').first().click();
  assert(await page.locator('#evidence-panel a[href*="rsarchive.org"]').count()>0,'outbound primary source missing');
  await page.goto(root+'/atlas/sources.html',{waitUntil:'networkidle'});
  await page.getByRole('heading',{name:'Find the original work behind a concept.'}).waitFor();
  const totalSources=await page.locator('#source-cards article').count();
  assert(totalSources>=53,'source guide has fewer than 53 original source cards');
  await page.locator('#filter-domain').selectOption('07');
  const limited=await page.locator('#source-cards article').count();
  assert(limited>0 && limited<totalSources,'source-guide domain filtering failed');
  await page.locator('#filter-kind').selectOption('recorded_lecture');
  const narrowed=await page.locator('#source-cards article').count();
  assert(narrowed>0 && narrowed<=limited,'source-guide work-kind filtering failed');
  await page.locator('#reset').click();
  assert(await page.locator('#source-cards article').count()===totalSources,'source-guide reset failed');
  await page.goto(root+'/atlas/coverage.html',{waitUntil:'networkidle'});
  await page.getByRole('heading',{name:'Evidence coverage across 150 subdomains'}).waitFor();
  const initialCoverage=await page.locator('#coverage-list article').count();
  assert(initialCoverage===150,'expected exactly 150 subdomains, found '+initialCoverage);
  await page.locator('#coverage-status').selectOption('none');
  const uncovered=await page.locator('#coverage-list article').count();
  assert(uncovered>0 && uncovered<150,'coverage status filter failed');
  await page.locator('#coverage-domain').selectOption('09');
  const filteredCoverage=await page.locator('#coverage-list article').count();
  assert(filteredCoverage<=uncovered,'coverage domain filter failed');
  await page.locator('#coverage-reset').click();
  assert(await page.locator('#coverage-list article').count()===150,'coverage reset failed');

  await page.goto(root+'/atlas/timeline.html',{waitUntil:'networkidle'});
  await page.getByRole('heading',{name:'Chronology of linked original lectures'}).waitFor();
  const lectureCards=await page.locator('.chronology-entry').count();
  assert(lectureCards>=18,'fewer than 18 dated original source records');
  const authoredWorks=await page.locator('.undated-card').count();
  assert(authoredWorks>=10,'authored books and essays not separately shown');
  await page.locator('#timeline-domain').selectOption('08');
  const karmaEvents=await page.locator('.chronology-entry').count();
  assert(karmaEvents>0 && karmaEvents<lectureCards,'timeline domain filter failed');
  await page.locator('#timeline-clear').click();
  assert(await page.locator('.chronology-entry').count()===lectureCards,'timeline reset failed');
  await page.goto(root+'/atlas/dossiers.html',{waitUntil:'networkidle'});
  await page.getByRole('heading',{name:"Follow a question across Steiner's original works."}).waitFor();
  const allDossiers=await page.locator('#dossier-list article').count();
  assert(allDossiers>=5,'dossier index missing original concept comparison guides');
  await page.locator('#dossier-search').fill('karma');
  assert(await page.locator('#dossier-list article').count()>0,'dossier search did not find karma');
  await page.goto(root+'/atlas/dossiers.html?id=human-constitution-schemes',{waitUntil:'networkidle'});
  await page.getByRole('heading',{name:/Four, seven, nine/}).waitFor();
  assert(await page.locator('.dossier-section').count()>=3,'dossier lacks substantial research sections');
  assert(await page.locator('.dossier-section a[href*="rsarchive.org"]').count()>=3,'dossier primary source links missing');
  await page.goto(root+'/atlas/trajectories.html',{waitUntil:'networkidle'});
  await page.getByRole('heading',{name:'One concept, several contexts'}).waitFor();
  assert(await page.locator('#trajectory-select option').count()>=7,'six concept trajectories not loaded');
  await page.locator('#trajectory-select').selectOption('eurythmy-june-july-1924');
  assert(await page.locator('.trajectory-card').count()===3,'dated lecture comparison has wrong count');
  const displayedDates=await page.locator('.trajectory-card time').allTextContents();
  assert(displayedDates.join(',')==='1924-06-24,1924-06-25,1924-07-07','original dated sequence incorrect');
  await page.locator('#trajectory-select').selectOption('human-constitution-contexts');
  assert(await page.locator('.trajectory-card').count()===3,'human constitution comparison missing');
  assert(await page.locator('.trajectory-card time').count()===1,'authored books must not inherit translation edition years');
  assert(await page.locator('.trajectory-card a[href*="rsarchive.org"]').count()===3,'source links missing in comparisons');
  await page.goto(root+'/atlas/organs.html',{waitUntil:'networkidle'});
  await page.getByRole('heading',{name:'Find Steiner’s accounts of individual organs.'}).waitFor();
  const organCount=await page.locator('#organ-nav [data-organ]').count();
  assert(organCount===26,'expected 26 comparative organ dossiers, found '+organCount);
  assert(await page.locator('#organ-detail h2').textContent()==='heart','default heart organ dossier not rendered');
  await page.locator('#organ-query').fill('pituitary');
  assert(await page.locator('#organ-nav [data-organ]').count()>=1,'organ search does not find pituitary');
  await page.locator('#organ-reset').click();
  await page.locator('#organ-nav [data-organ="organ-bladder"]').click();
  assert((await page.locator('#organ-detail h2').textContent()).includes('bladder'),'bladder case dossier unavailable');
  assert(await page.locator('#organ-detail a[href*="rsarchive.org"]').count()>0,'selected-only source link missing');
  assert(await page.locator('#case-summary details').count()===2,'case passage audit or translation discrepancy not rendered');
  await page.locator('#case-summary details').last().locator('summary').click();
  assert(await page.locator('#case-summary details').last().locator('article').count()===2,'expected two bilingual numerical discrepancies');
  assert(!errors.length,'console or page errors: '+errors.join('; '));
  console.log(JSON.stringify({ok:true,conceptSearch:true,domainRows,compared,sourceRows,totalRelationships:initial}));
  await page.close();
  const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,deviceScaleFactor:2});
  await ready(mobile);
  await mobile.goto(root+'/atlas/',{waitUntil:'networkidle'});
  await mobile.getByRole('heading',{name:'Find the teaching, then read the original.'}).waitFor();
  await mobile.goto(root+'/atlas/graph.html',{waitUntil:'networkidle'});
  await mobile.getByRole('heading',{name:'Follow the evidence between teachings'}).waitFor();
  assert(await mobile.locator('#source-filter').isVisible(),'mobile graph controls hidden');
  await mobile.goto(root+'/atlas/coverage.html',{waitUntil:'networkidle'});
  await mobile.locator('#coverage-domain').waitFor();
  assert(await mobile.locator('#coverage-status').isVisible(),'mobile coverage filtering unavailable');
  await mobile.goto(root+'/atlas/timeline.html',{waitUntil:'networkidle'});
  assert(await mobile.locator('#timeline-from').isVisible(),'mobile timeline unavailable');
  await mobile.goto(root+'/atlas/dossiers.html',{waitUntil:'networkidle'});
  assert(await mobile.locator('#dossier-search').isVisible(),'mobile dossiers search unavailable');
  await mobile.goto(root+'/atlas/trajectories.html',{waitUntil:'networkidle'});
  assert(await mobile.locator('#trajectory-select').isVisible(),'mobile comparison selector unavailable');
  await mobile.goto(root+'/atlas/organs.html',{waitUntil:'networkidle'});
  assert(await mobile.locator('#organ-query').isVisible(),'mobile organ search unavailable');
  assert(await mobile.locator('#organ-nav [data-organ]').count()===26,'mobile organ dossiers not loaded');
  assert(!errors.length,'mobile console or page errors: '+errors.join('; '));
  await mobile.close();
  console.log('PASS: desktop + mobile atlas routes, search, source links, domain/evidence filtering');
} catch(e) {
  console.error(e);
  process.exitCode=1;
} finally { await browser.close(); }
